function getOverdueLeads(thresholdHours) {
  const hours = Number(thresholdHours) || 2;
  const leads = getAllLeads();
  const now = new Date().getTime();
  
  return leads.filter(l => {
    if (l.status === 'Closing' || l.status === 'Ghost') return false;
    if (!l.lastContact) return true; // Never contacted
    const contactTime = new Date(l.lastContact).getTime();
    if (isNaN(contactTime)) return true;
    const diffHours = (now - contactTime) / (1000 * 60 * 60);
    return diffHours >= hours;
  });
}

function advanceLeadTouchAndStatus(leadId, newStatus) {
  const sheet = getSheet(SHEET_NAMES.WAR_ROOM);
  if (!sheet) throw new Error('War Room not found');
  const row = findRowByLeadId(sheet, leadId);
  
  // Touch Count + 1
  const currentTouch = Number(sheet.getRange(row, COL_WAR.TOUCH).getValue()) || 0;
  sheet.getRange(row, COL_WAR.TOUCH).setValue(currentTouch + 1);
  
  // Last Contact Date = Now
  const nowStr = new Date().toISOString().replace('T', ' ').substring(0, 19);
  sheet.getRange(row, COL_WAR.LAST_CONTACT).setValue(nowStr);
  
  // Update status if provided
  if (newStatus) {
    sheet.getRange(row, COL_WAR.STATUS).setValue(newStatus);
  }
  
  return { success: true, newTouch: currentTouch + 1, lastContact: nowStr };
}

// --- GOOGLE DOC REPORT GENERATOR FOR CLIENTS ---

function generateClientGoogleDocReport(clientName, reportType) {
  if (!clientName) throw new Error('Client Name is required');
  const type = reportType || 'Weekly';
  
  // Fetch stats for this client
  const leads = getLeadsByClient(clientName);
  const stats = getDashboardStatsByClient(clientName);
  
  // Ensure Folder 'ZK Revenue Reports' exists in Google Drive
  let folder;
  const folders = DriveApp.getFoldersByName('ZK Revenue Reports');
  if (folders.hasNext()) {
    folder = folders.next();
  } else {
    folder = DriveApp.createFolder('ZK Revenue Reports');
  }
  
  // Create Google Doc
  const dateStr = Utilities.formatDate(new Date(), Session.getScriptTimeZone(), 'yyyy-MM-dd');
  const docTitle = `ZK RevOps — ${clientName} (${type} Report) — ${dateStr}`;
  const doc = DocumentApp.create(docTitle);
  const docFile = DriveApp.getFileById(doc.getId());
  
  // Move file into ZK Revenue Reports folder
  folder.addFile(docFile);
  DriveApp.getRootFolder().removeFile(docFile);
  
  // Populate Document Content
  const body = doc.getBody();
  body.clear();
  
  // Document Title Header
  const titleHeader = body.appendParagraph(`ZK REVENUE OPERATIONS — EXECUTIVE REPORT`);
  titleHeader.setHeading(DocumentApp.ParagraphHeading.HEADING1);
  titleHeader.setFontFamily('Arial');
  
  body.appendParagraph(`Client: ${clientName}`);
  body.appendParagraph(`Report Type: ${type} Executive Performance Briefing`);
  body.appendParagraph(`Date Generated: ${dateStr}`);
  body.appendHorizontalRule();
  
  // Metrics Summary Section
  body.appendParagraph(`1. PIPELINE METRICS SUMMARY`).setHeading(DocumentApp.ParagraphHeading.HEADING2);
  body.appendParagraph(`• Total Active Prospects: ${stats.totalLeads || 0}`);
  body.appendParagraph(`• HOT Rated Prospects: ${stats.hotLeads || 0}`);
  body.appendParagraph(`• Scheduled Viewings: ${stats.appointments || 0}`);
  body.appendParagraph(`• Total Pipeline Value: RM ${(stats.pipelineValue || 0).toLocaleString()}`);
  body.appendParagraph(`• Projected Commission (3%): RM ${(stats.estCommission || 0).toLocaleString()}`);
  
  body.appendParagraph(``);
  
  // Active Hot Leads Section
  body.appendParagraph(`2. HIGH INTENT PROSPECTS (HOT QUEUE)`).setHeading(DocumentApp.ParagraphHeading.HEADING2);
  const hotLeads = leads.filter(l => l.status === 'Hot' || l.status === 'Appointment');
  if (hotLeads.length === 0) {
    body.appendParagraph(`No HOT prospects currently in queue.`);
  } else {
    hotLeads.forEach((l, index) => {
      body.appendParagraph(`${index + 1}. ${l.name} — ${l.property || 'General'} (RM ${Number(l.price || 0).toLocaleString()})`);
      body.appendParagraph(`   WhatsApp: ${l.wa} | Status: ${l.status} | Touches: ${l.touch || 1}`);
      if (l.notes) body.appendParagraph(`   Notes: ${l.notes}`);
    });
  }
  
  body.appendParagraph(``);
  
  // Recommendations Section
  body.appendParagraph(`3. AI SDR RECOMMENDATIONS & NEXT ACTIONS`).setHeading(DocumentApp.ParagraphHeading.HEADING2);
  body.appendParagraph(`• Closing Velocity: Pipeline value stands at RM ${(stats.pipelineValue || 0).toLocaleString()}. Priority recommendation is to finalize viewings for the ${stats.hotLeads || 0} HOT prospects.`);
  body.appendParagraph(`• Touch Discipline: Maintain touch frequency above 3 touches per prospect to preserve engagement velocity.`);
  
  doc.saveAndClose();
  
  // Store doc URL in Properties Service or return directly
  const docUrl = doc.getUrl();
  PropertiesService.getScriptProperties().setProperty('report_' + clientName.trim().toLowerCase(), docUrl);
  
  return {
    success: true,
    docUrl: docUrl,
    docId: doc.getId(),
    title: docTitle
  };
}